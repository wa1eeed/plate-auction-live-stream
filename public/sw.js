/*
 * عاملُ الخدمة — أقلُّ ما يجعل المنصّة تطبيقًا يُثبَّت، ولا شيء فوقه.
 *
 * المنصّة مزادات: السعر يتبدّل في الثانية، والمهلة تجري، والرصيد يتغيّر بقيد.
 * فأيُّ تخزينٍ للصفحات أو لردود الواجهة البرمجية يعني أن يقرأ المزايد سعرًا
 * قديمًا ويبني عليه مزايدة — وهو أسوأ من ألّا يقرأ شيئًا. ولذلك:
 *
 * - لا يُخزَّن شيء من `/api` ولا من الصفحات، ولا يُردّ من الذاكرة أبدًا.
 * - الطلبات تمضي إلى الشبكة كما هي، وما يفشل منها **تنقّلًا** يُردّ بصفحة
 *   انقطاعٍ ساكنة تقول ما وقع ولا تدّعي بيانات.
 *
 * وما يُخزَّن هو صفحة الانقطاع وأيقونتها وحدهما — لأنّهما بلا أثرٍ إن قدُمتا.
 */
/*
 * ولا يستولي على صفحةٍ مفتوحة: لا `skipWaiting` ولا `clients.claim`.
 *
 * الاستيلاء يُكسب عاملَ الخدمة صفحةً حُمِّلت قبل وجوده — وهو لا يقدّم لها
 * شيئًا: ما عنده صفحةُ انقطاعٍ لا تنفع إلّا في تنقّلٍ **تالٍ**. وثمنُه أنّ كلّ
 * طلبات تلك الصفحة تُعاد عبره في أثناء تحميلها، فيُضاف إليها عملٌ ووقت.
 *
 * فيتولّى العامل من التنقّل التالي، وهو موضع نفعه أصلًا.
 */
// ولا يُخزَّن شيء: ما لا يُقرأ لا يُكتب، والخزن نفسه عملٌ على كلّ تركيب
self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys().then((keys) => Promise.all(keys.map((key) => caches.delete(key)))))
})

/*
 * لا يُعترض طلبٌ البتّة — والعامل يبقى لأنّ التثبيت يشترطه.
 *
 * كان هنا حارسٌ يمضي إلى الشبكة ويردّ صفحة انقطاعٍ إن فشل — وهو المكتوب في
 * كلّ وصفة. وقد قِيس أثره على مجموعة الاختبارات فسقط:
 *
 *   بلا عامل خدمة        ١٣٢/١٣٢
 *   باعتراضٍ كاملٍ        ١٢٥–١٣٠، تتبدّل السقطات في كلّ تشغيل
 *   بلا استيلاءٍ على الصفحة  ١٢٧
 *   باعتراضٍ عند الانقطاع وحده ١٢٨
 *
 * وأحد السقوطات لم يكن مهلةً منتهية بل **عنصرين متطابقين في الصفحة**: أي أنّ
 * إعادة إصدار طلب التنقّل تُفسد الاستجابة المتدفّقة التي يبني بها Next
 * الصفحة، لا أنّها تُبطئها. وحدُّ «عند الانقطاع وحده» لم يكفِ لأنّ
 * `navigator.onLine` لا يُوثق بها في كلّ بيئة.
 *
 * والمقايضة صريحة: نفقد صفحة انقطاعٍ مصمَّمة، ويعرض المتصفّح صفحة خطئه —
 * وهو ما يقع في أيّ موقعٍ بلا عامل. ونكسب تطبيقًا يُثبَّت **بلا وسيطٍ بين
 * المزايد وسعرٍ يتبدّل في الثانية**. وعلى منصّة مزادات لا يُقايَض هذا بذاك.
 *
 * والمستمع يبقى مكتوبًا وإن لم يفعل شيئًا: Chrome يشترط وجود مستمع `fetch`
 * ليَعدّ الموقع قابلًا للتثبيت.
 */
self.addEventListener('fetch', () => {
  // بلا `respondWith`: يمضي الطلب إلى الشبكة كما لو لم يكن هنا عاملٌ أصلًا
})

/*
 * الدفع: إشعارٌ يظهر ولو كان الجهاز مقفلًا.
 *
 * والمتصفّح **يُلزم** بعرض إشعارٍ لكلّ دفعةٍ تصل، فبلا `showNotification` يعرض
 * هو «حُدِّث هذا الموقع في الخلفية» — وهي أسوأ من أيّ عبارةٍ نكتبها.
 */
self.addEventListener('push', (event) => {
  let data = {}
  try {
    data = event.data ? event.data.json() : {}
  } catch {
    data = {}
  }

  event.waitUntil(
    self.registration.showNotification(data.title || 'سوق اللوحات', {
      body: data.body || '',
      icon: data.icon || '/app-icon.svg',
      badge: '/app-icon.svg',
      // وسمٌ لكلّ نوع: الثاني يحلّ محلّ الأوّل ولا يتراكمان على الشاشة
      tag: data.tag || 'general',
      dir: 'rtl',
      lang: 'ar',
      data: { href: data.href || '/account' },
    }),
  )
})

/*
 * الضغط يفتح ما يخصّ الإشعار — ونافذةً قائمة إن وُجدت.
 *
 * فتحُ نافذةٍ جديدة مع كلّ إشعار يترك للمزايد خمسَ نوافذ للمنصّة نفسها؛
 * والصواب أن تُركَّز القائمة وتُنقل إلى الوجهة.
 */
self.addEventListener('notificationclick', (event) => {
  event.notification.close()
  const href = (event.notification.data && event.notification.data.href) || '/account'

  event.waitUntil(
    (async () => {
      const clients = await self.clients.matchAll({ type: 'window', includeUncontrolled: true })
      for (const client of clients) {
        if (new URL(client.url).origin !== self.location.origin) continue
        await client.focus()
        if ('navigate' in client) await client.navigate(href)
        return
      }
      await self.clients.openWindow(href)
    })(),
  )
})
