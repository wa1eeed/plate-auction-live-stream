import { describe, expect, it } from 'vitest'
import { markOf, shouldChime, type ChimeMark } from '@/lib/notification-chime'

/**
 * **نبرةٌ لكلّ إشعارٍ جديد مرّةً — لا لكلّ فتحةِ صفحة.**
 *
 * وكان الحارسُ عدّادًا في الذاكرة يبدأ صفرًا مع كلّ تركيب، فأوّلُ مزامنةٍ
 * بعد أيّ تحميلٍ ترى «غيرُ المقروء أكبرُ من صفر» فتُنبّه. فمن عنده إشعارٌ
 * واحدٌ لم يقرأه يسمع النبرةَ في كلّ صفحةٍ يدخلها وكلّ مرّةٍ يُحدّث فيها.
 */
const n = (id: string, createdAt: string) => ({ id, createdAt })
const mark = (id: string, at: string): ChimeMark => ({ id, at })

describe('متى يُنبَّه بإشعار', () => {
  it('لا إشعاراتٍ ⇒ لا نبرة', () => {
    expect(shouldChime(undefined, mark('n1', '2026-10-20T10:00:00.000Z'))).toBe(false)
  })

  /*
   * **وأوّلُ مزامنةٍ في متصفّحٍ لم يُزامَن قطّ صامتة.**
   *
   * فمن فتح المنصّة لأوّل مرّة لا يُستقبل بنبرةٍ عن إشعارٍ وصله أمس —
   * وهو العطبُ نفسُه الذي كان يتكرّر مع كلّ فتحة.
   */
  it('وأوّلُ مزامنةٍ بلا علامةٍ محفوظة لا تُنبّه', () => {
    expect(shouldChime(n('n9', '2026-10-21T08:00:00.000Z'), null)).toBe(false)
  })

  /*
   * **وهذا هو العطبُ بعينه**: الإشعارُ نفسُه بعد تحميلٍ ثانٍ، وثالث، ورابع.
   */
  it('والإشعارُ نفسُه لا يُعاد مهما فُتحت الصفحة', () => {
    const latest = n('n9', '2026-10-21T08:00:00.000Z')
    const seen = markOf(latest)
    expect(shouldChime(latest, seen)).toBe(false)
    expect(shouldChime(latest, seen)).toBe(false)
    expect(shouldChime(latest, seen)).toBe(false)
  })

  it('وأحدثُ منه يُنبّه مرّةً', () => {
    const seen = markOf(n('n9', '2026-10-21T08:00:00.000Z'))
    const fresh = n('n10', '2026-10-21T09:00:00.000Z')
    expect(shouldChime(fresh, seen)).toBe(true)
    /* ثمّ تُسجَّل علامتُه فلا يُعاد */
    expect(shouldChime(fresh, markOf(fresh))).toBe(false)
  })

  /*
   * فحذفُ أحدثِ إشعارٍ يجعل الذي يليه «أحدثَ القائمة» ومعرّفُه مختلف —
   * فلو كان تبدّلُ المعرّف وحده شرطًا لنُبِّه على قديمٍ قُرئ من زمن.
   */
  it('وأقدمُ منه لا يُنبّه وإن تبدّل المعرّف', () => {
    const seen = markOf(n('n10', '2026-10-21T09:00:00.000Z'))
    expect(shouldChime(n('n9', '2026-10-21T08:00:00.000Z'), seen)).toBe(false)
  })

  /*
   * ومن زامن وقائمتُه فارغة تُسجَّل له علامةٌ فارغة — فأوّلُ واردٍ بعدها
   * يُنبَّه به. ولولا ذلك لصمتت المنصّةُ عن أوّل إشعارٍ في حياة الحساب.
   */
  it('ومن زامن بلا إشعاراتٍ يُنبَّه بأوّلِ وارد', () => {
    const empty = markOf(undefined)
    expect(empty).toEqual({ id: '', at: '' })
    expect(shouldChime(n('n1', '2026-10-21T09:00:00.000Z'), empty)).toBe(true)
  })

  /*
   * **وإشعاران في المللي ثانية نفسِها خبران.**
   *
   * و`notifyMany` تكتب دفعةً واحدة، فتتساوى الأختام. ولو كان الشرطُ `>`
   * وحده لصمتت المنصّةُ عن الوارد الثاني — وهو وارِدٌ حقيقيّ.
   */
  it('وواردٌ بالختم نفسِه ومعرّفٍ آخرَ يُنبَّه به', () => {
    const at = '2026-10-21T08:00:00.000Z'
    expect(shouldChime(n('n11', at), markOf(n('n10', at)))).toBe(true)
  })

  /*
   * والعدَدُ ليس خبرًا: يرتفع بالوارد وينخفض بالقراءة ثمّ يرتفع بما قُرئ
   * على جهازٍ آخر — والنبرةُ تتبع الإشعارَ لا العدّاد.
   */
  it('وقراءةُ الإشعارات ثمّ عودتُها غيرَ مقروءةٍ لا تُنبّه', () => {
    const latest = n('n9', '2026-10-21T08:00:00.000Z')
    const seen = markOf(latest)
    /* قُرئ على جهازٍ آخر فعاد العدّاد صفرًا ثمّ ارتفع — والإشعارُ هو هو */
    expect(shouldChime(latest, seen)).toBe(false)
  })
})
