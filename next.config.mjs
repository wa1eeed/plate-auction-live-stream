/**
 * إعداد Next بصيغة `.mjs` لا `.ts` — عمدًا.
 *
 * إعدادُ TypeScript يُحمَّل وقت **التشغيل** لا وقت البناء وحده: يطلب Next حزمة
 * `typescript` من `node_modules` ليترجم الملفّ، وإن لم يجدها **حاول تنزيلها من
 * الشبكة أثناء الإقلاع**. وذلك يربط إقلاع الحاوية بالإنترنت وبحزمة تطوير لا
 * موضع لها في صورة الإنتاج. والتعليق أدناه يعطي التحقّق من الأنواع في المحرّر
 * كما كان، بلا اعتماد وقت التشغيل.
 *
 * @type {import('next').NextConfig}
 */
const nextConfig = {
  reactStrictMode: true,
  eslint: { ignoreDuringBuilds: false },
  experimental: { optimizePackageImports: ['lucide-react'] },

  /**
   * سائق القاعدة يبقى خارج الحزمة.
   *
   * `pg` يستورد `pg-native` استيرادًا اختياريًّا — إضافةً أصيلةً لا تُثبَّت
   * عندنا — فيحاول Next حزمَها فيسقط البناء بـ«Module not found». وهو خارج
   * المتصفّح أصلًا: يُطلَب في العملية وقت التشغيل لا يُحزَم في ملفّ.
   */
  serverExternalPackages: ['pg'],
  /**
   * مجلّد المخرجات قابل للتبديل عبر البيئة.
   * السبب: `pnpm test:e2e` يبني مبنى إنتاج، وإن كتبه في `.next` نفسه الذي
   * يستخدمه خادم التطوير العامل استبدل ملفاته، فترجع الحُزم 404 وتظهر
   * الصفحات بلا تنسيق ولا تفاعل. الاختبار الشامل يستخدم مجلّدًا خاصًّا به.
   */
  distDir: process.env.NEXT_DIST_DIR ?? '.next',

  /**
   * لكل مجلّد مخرجات ملفّ إعداد خاص به.
   * أنواع المسارات المولّدة تعيش داخل مجلّد المخرجات، فلو اجتمع مجلّدان في
   * `include` واحد تضاربت نسختان من النوع نفسه وسقط البناء.
   */
  typescript: {
    tsconfigPath: process.env.NEXT_DIST_DIR ? 'tsconfig.e2e.json' : 'tsconfig.json',
  },

  /**
   * `/@waleed` رابطُ المعرض، و`/u/[id]` مسارُه.
   *
   * الرابط يُملى في مجلس ويُكتب في وصف حساب، فكلّ حرفٍ زائد فيه يُقرأ. و`@`
   * وحدها تقول إنّ ما بعدها شخص — وهي العُرف الذي يعرفه الناس من إكس وثريدز.
   *
   * ولا يُكتب مجلّدًا باسم `@`: البادئة محجوزة في Next للمسارات المتوازية،
   * فيُفهم `app/@waleed` فتحةَ تصيير لا جزءًا من العنوان. والتحويل يفصل ما
   * يُقرأ عمّا يُصيَّر: العنوان جميل والمسار واحد.
   *
   * و`/u/<المعرّف>` يبقى عاملًا: من لم يختر معرّفًا علنيًّا بعد له رابط، ومن
   * غيّره لا تنكسر عليه روابطُ أُرسلت.
   */
  async rewrites() {
    return [{ source: '/@:handle', destination: '/u/:handle' }]
  },

  /**
   * ترويسات الأمان الساكنة — ما لا يتغيّر بين طلبٍ وطلب.
   *
   * وأمّا `Content-Security-Policy` فليست هنا: تحتاج `nonce` يُولَّد لكلّ
   * طلب، فموضعُها `middleware.ts`.
   *
   * ولماذا هنا لا في الوسيط كلُّها؟ لأنّ ما لا يحتاج حسابًا لا يُحسب في كلّ
   * طلب — وهذه يضعها Next مرّةً في جدول التوجيه.
   */
  async headers() {
    return [
      {
        source: '/:path*',
        headers: [
          /*
           * سنةٌ كاملة، والنطاقات الفرعية معها.
           *
           * وبلا هذه الترويسة يكفي طلبٌ واحد على HTTP ليُعترض قبل أن يصل
           * التحويل إلى HTTPS — وفيه كوكي الجلسة إن لم يكن `Secure`.
           *
           * ولا `preload` بعد: إدراج النطاق في قائمة المتصفّحات المسبقة
           * **لا يُتراجع عنه بسهولة**، ويشمل كلّ نطاقٍ فرعيّ إلى الأبد. وهي
           * خطوةٌ تُؤخذ بعد أن يستقرّ النطاق وفروعُه، لا مع أوّل إطلاق.
           */
          { key: 'Strict-Transport-Security', value: 'max-age=31536000; includeSubDomains' },

          /* المتصفّح لا يخمّن نوع الملفّ — ومرفوعٌ يُخمَّن سكربتًا يُنفَّذ */
          { key: 'X-Content-Type-Options', value: 'nosniff' },

          /*
           * لا تُوضع المنصّة في إطار.
           *
           * ومعها `frame-ancestors` في الـCSP — وهي الأحدث والأدقّ. وتبقى
           * هذه للمتصفّحات القديمة التي لا تقرأ تلك.
           */
          { key: 'X-Frame-Options', value: 'DENY' },

          /*
           * المسار الكامل لا يُرسل إلى موقعٍ آخر — وفيه معرّفات إعلانات
           * ومستخدمين. والأصل وحده يكفي لمن يقيس مصادر زيارته.
           */
          { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },

          /*
           * صلاحيات الجهاز مغلقةٌ كلُّها: المنصّة لا تطلب كاميرا ولا ميكروفون
           * ولا موقعًا. وإغلاقُها يمنع كودًا دخيلًا من طلبها باسم النطاق.
           */
          {
            key: 'Permissions-Policy',
            value: 'camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()',
          },

          /* عبر النطاقات: لا يُفتح مورد المنصّة من موقعٍ آخر */
          { key: 'Cross-Origin-Opener-Policy', value: 'same-origin' },
          { key: 'Cross-Origin-Resource-Policy', value: 'same-origin' },
        ],
      },
    ]
  },
}

export default nextConfig
