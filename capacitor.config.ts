import type { CapacitorConfig } from '@capacitor/cli'

/**
 * إعدادُ الغلاف الأصيل — تطبيقٌ واحد يُخرج iOS وأندرويد.
 *
 * ولماذا `server.url` لا حزمةٌ ساكنة؟ لأنّ الواجهة **تُصيَّر على الخادم**:
 * خمسٌ وأربعون صفحةً كلُّها مكوّنات خادم، وتسعٌ وثمانون ملفًّا تعلن
 * `force-dynamic`، والجلسة تُقرأ خادميًّا في ثمانين موضعًا بكوكي `httpOnly`.
 * فلا مبنًى ساكنًا يُحزَم، ولا يُستخرج إلّا بإعادة كتابة المنصّة — انظر
 * [MOBILE_APP_IMPLEMENTATION_PLAN.md](./MOBILE_APP_IMPLEMENTATION_PLAN.md).
 *
 * **وليس هذا إطارًا حول موقع.** الغلاف يحمل طبقةً أصيلة حقيقية: إشعارات
 * APNs و FCM، وروابط كونية، وشاشة إقلاع، وشريط حالة، وزرّ رجوع، واهتزازًا،
 * وورقة مشاركة — ويتخاطب مع الواجهة عبر جسرٍ برمجيّ.
 *
 * وميزةٌ لا تُشترى بغيرها: الأصل يبقى نطاقَ المنصّة نفسه، فتبقى كوكي
 * الجلسة `httpOnly` عاملةً كما هي. ولو حُزمت الواجهة لصار الأصل
 * `capacitor://` فتصير الكوكي عابرةَ موقعٍ ولا تُرسَل مع `sameSite=lax` —
 * فيلزم رمزٌ يُحفظ في الجهاز، وهو سطحُ أمانٍ جديد بلا مقابل.
 */
/*
 * **ولا نطاقَ إنتاجٍ مكتوبٌ هنا.** الافتراضيُّ تطويرٌ محض، فنسيانُ المتغيّر
 * يُخرج تطبيقًا يقرأ من `localhost` — عطبٌ يُرى في أوّل فتحة. وكتابةُ نطاقٍ
 * حقيقيٍّ هنا تُخرج تطبيقًا يقرأ من نطاقٍ **قديم** بلا أن يشكو أحد، وهو ما
 * وقع في `v1.0.3`. والصامتُ أسوأ من الصارخ.
 */
const appUrl = process.env.NEXT_PUBLIC_APP_URL?.replace(/\/$/, '') ?? 'http://localhost:3000'

/**
 * **نطاقُ التطبيق يُخبز في الملفّ — فليكن نطاقًا لا يتغيّر.**
 *
 * `server.url` يُكتب في الحزمة وقت البناء، فتغييرُ النطاق يُعطّل كلَّ نسخةٍ
 * مثبَّتة حتى تمرّ نسخةٌ جديدة بمراجعة المتجر — أيّامًا لا ساعات. وقد وقع:
 * نُقل النطاق إلى `payone.one` فصار `mazad.nx.sa` يردّ 503، والتطبيقاتُ
 * المثبَّتة تقرأ من ميّت.
 *
 * فالقاعدة: **نطاقُ الغلاف شيءٌ ونطاقُ العلامة شيء**. الأوّل يُختار مرّةً
 * ويبقى، والثاني يتبدّل بالتسويق كما يشاء — ويُحوَّل إلى الأوّل أو يخدم
 * المحتوى نفسه.
 *
 * ولهذا تُقبل نطاقاتٌ إضافية في `CAPACITOR_ALLOWED_HOSTS` مفصولةً بفاصلة:
 * تُخبز في البناء فتبقى مقبولةً للتنقّل داخل الغلاف. فمن أراد نقلًا مستقبليًّا
 * أدرج نطاقه الجديد **قبل** النقل، ثمّ نقل متى شاء بلا بناءٍ ثانٍ.
 */
const allowedHosts = [
  ...new Set(
    [
      new URL(appUrl).host,
      ...(process.env.CAPACITOR_ALLOWED_HOSTS ?? '')
        .split(',')
        .map((host) => host.trim())
        .filter(Boolean),
    ],
  ),
]

const config: CapacitorConfig = {
  appId: 'sa.nx.mazad',
  appName: 'سوق اللوحات',

  /*
   * مجلّدٌ يُحزَم ولا يُعرض في الحال المعتاد.
   *
   * Capacitor يشترط `webDir` موجودًا، والتطبيق يفتح الخادم. وما فيه صفحةُ
   * تعذّرٍ ساكنة تظهر متى انقطع الوصول — فيقرأ صاحبها سببًا بدل شاشةٍ بيضاء.
   */
  webDir: 'capacitor/www',

  server: {
    url: appUrl,
    /*
     * `cleartext: false` صراحةً: لا HTTP بلا تشفير في أيّ حال.
     * والجلسة تسافر في الكوكي، فنقلُها على قناةٍ مكشوفة لا يُحتمل.
     */
    cleartext: false,
    /*
     * النطاقاتُ المسموحة للتنقّل داخل التطبيق، وما عداها يُفتح في متصفّح
     * النظام. ورابطٌ خارجيّ يُفتح داخل الغلاف يُخفي شريطَ العنوان عمّن يحتاجه
     * ليعرف أين هو — وهو باب تصيّد.
     *
     * وإدراجُ نطاقٍ هنا **لا** يُحوّل التطبيق إليه: `server.url` وحده يفعل.
     * وإنّما يجعل التحويلَ إليه ممكنًا بلا بناءٍ جديد — انظر `allowedHosts`.
     */
    allowNavigation: allowedHosts,
  },

  ios: {
    /*
     * الخلفية تُطابق `theme_color` في البيان و`themeColor` في التخطيط.
     * ثلاثةُ ألوانٍ تختلف تُنتج وميضًا عند الإقلاع وعند شدّ الصفحة.
     */
    backgroundColor: '#f4f6fa',
    /** شدّ الصفحة لا يكشف خلفيةً بيضاء تحت المحتوى */
    scrollEnabled: true,
    contentInset: 'always',
  },

  android: {
    backgroundColor: '#f4f6fa',
    /** لا نسمح بمحتوى مكشوف — يطابق `cleartext: false` أعلاه */
    allowMixedContent: false,
    captureInput: true,
  },

  plugins: {
    SplashScreen: {
      /*
       * تُخفى بأمرٍ من الواجهة لا بمؤقّت.
       *
       * المؤقّت يخمّن متى صارت الصفحة جاهزة: إن قصُر ظهرت شاشةٌ بيضاء تحته،
       * وإن طال انتظر صاحبُه بلا سبب. والواجهة تعرف اللحظة فتأمر بإخفائها.
       */
      launchAutoHide: false,
      backgroundColor: '#f4f6fa',
      androidScaleType: 'CENTER_CROP',
      showSpinner: false,
    },
    PushNotifications: {
      /** الشارة والصوت والتنبيه — والمستخدم يضبطها من نظامه بعدُ */
      presentationOptions: ['badge', 'sound', 'alert'],
    },
    Keyboard: {
      /*
       * لوحة المفاتيح **تُصغّر النافذة** لا تعلو عليها.
       *
       * و`native` (الافتراضيّ على iOS) يُزلق المحتوى كلَّه لأعلى فيخرج
       * الهيدر من الشاشة، ويبقى الحقل خلف اللوحة إن كان أسفلها. و`body`
       * يُصغّر نافذة العرض فيُعاد التخطيط: الحقل فوقها والزرّ معه.
       *
       * وهذا يمسّ حقل المزايدة تحديدًا: هو في **شريطٍ ثابت أسفل الشاشة**،
       * وهو أوّل ما تغطّيه اللوحة.
       */
      resize: 'body',
      /* لا شريط «تمّ» فوق اللوحة: يُضيف صفًّا غريبًا عن هويّة المنصّة */
      resizeOnFullScreen: true,
    },
  },
}

export default config
