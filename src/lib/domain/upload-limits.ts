/**
 * حدودُ الرفع بالبايت — **مصدرٌ واحد يقرؤه الخادم والمتصفّح**.
 *
 * والخادمُ يبقى الحَكَم: يقيس البايتات المقروءة ويردّ `413`. لكنّ ردَّه
 * **قبل قراءة الجسم** لا يبلغ المتصفّحَ رسالةً — يغلق الخادمُ الوصلةَ
 * والمتصفّحُ ما زال يرفع، فيُجهَض الطلب ويقع `fetch` في `catch`، فيُقرأ
 * «تعذّر الاتّصال بالخادم»: عطلُ شبكةٍ موهوم، والملفُّ إنّما كان كبيرًا.
 *
 * فيُقاس الحجمُ في المتصفّح **قبل** أن يُرسل. وهذا لا يستبدل حراسةَ الخادم
 * ولا ينقص منها — إنّما يمنع طلبًا محكومًا بالفشل، ويقول للرافع كم ملفُّه
 * وكم الحدّ بدل أن يُحيله على الشبكة.
 */
export const UPLOAD_LIMITS = {
  'image/jpeg': 4 * 1024 * 1024,
  'image/png': 4 * 1024 * 1024,
  'image/webp': 4 * 1024 * 1024,
  /*
   * مئتا ميغابايت للفدّيو — وكان أربعةً وعشرين.
   *
   * والأربعةُ والعشرون لم تكن حدَّ R2 يومًا، بل حدَّ **ذاكرة الحاوية**: الخادم
   * كان يحمل الملفّ كلَّه ليحكم على بايتاته. وبالرفع المباشر لم يعد يحمل
   * شيئًا، فسقط القيدُ الذي فرضه.
   */
  'video/mp4': 200 * 1024 * 1024,
  'video/quicktime': 200 * 1024 * 1024,
  'application/pdf': 8 * 1024 * 1024,
} as const

/**
 * سقفُ الرفع **عبر الخادم** — وهو غيرُ سقف الرفع المباشر.
 *
 * والمسلك القديم يقرأ الملفّ كلَّه إلى الذاكرة، فمئتا ميغابايت فيه تعني
 * حاويةً تُقتل. وهو مسلكُ محرّك القرص (التطوير والفحص) ومسلكُ الرجوع متى
 * تعذّر التوقيع — وكلاهما لا يحتاج فدّيو بمئتَي ميغابايت.
 */
export const PROXY_MAX_BYTES = 24 * 1024 * 1024

export type LimitedMime = keyof typeof UPLOAD_LIMITS

/** حدُّ نوعٍ ما، أو `null` لنوعٍ لا نعرفه — فيحكم فيه الخادم وحده. */
export function limitFor(mime: string): number | null {
  return (UPLOAD_LIMITS as Record<string, number | undefined>)[mime] ?? null
}

/** أكبرُ حدٍّ في الجدول — وعنده يردّ الخادم **قبل أن يقرأ الجسم**. */
export const MAX_UPLOAD_BYTES = Math.max(...Object.values(UPLOAD_LIMITS))

const megabytes = (bytes: number): string =>
  (bytes / (1024 * 1024)).toFixed(1).replace(/\.0$/, '')

const SUPPORTED = 'JPEG و PNG و WebP للصور، و MP4 للفدّيو'

/**
 * سببُ الردّ قبل الإرسال، أو `null` إن كان الملفّ مقبولًا.
 *
 * **ونوعٌ لا نعرفه لا يُترك يمرّ.** كان يُترك — فيُعاد له `null` ولا يُقاس
 * حجمُه — وذلك بابُ العطب كلِّه: فدّيو الآيفون يأتي `video/quicktime` لا
 * `video/mp4`، فيمرّ بلا قياسٍ مهما كبر. ثمّ يردّ الخادم `413` على ترويسة
 * الحجم **قبل أن يقرأ الجسم**، فيغلق الوصلةَ والمتصفّحُ ما زال يضخّ —
 * فيُجهَض الطلب: `ECONNRESET` عند الخادم، و`ERR_TIMED_OUT` عند المتصفّح،
 * ولا تصل رسالةٌ إلى أحد. فتُقرأ «تعذّر الاتّصال بالخادم» والشبكةُ سليمة.
 *
 * والترتيب مقصود: **الحجمُ أوّلًا**. فملفٌّ ضخمٌ بنوعٍ غير مدعوم عطبُه
 * الأوّل حجمُه — وهو الذي يقطع الوصلة — لا صيغتُه.
 */
export function uploadRejection(mime: string, bytes: number): string | null {
  const limit = limitFor(mime)

  if (bytes > (limit ?? MAX_UPLOAD_BYTES)) {
    return `الملفّ ${megabytes(bytes)} ميغابايت والحدّ ${megabytes(limit ?? MAX_UPLOAD_BYTES)} — اختر ملفًّا أصغر`
  }
  /*
   * والنوعُ المجهول يُردّ هنا لا في الخادم — وكان الخادم يردّه `415` برسالةٍ
   * تصل فعلًا (لأنّه يقرأ الجسم أوّلًا)، لكنّ ذلك يعني رفعَ ملفٍّ كاملٍ
   * ليُقال «غير مدعوم». والقائمةُ معروفةٌ للطرفين، فلا معنى لرفعه.
   */
  if (limit === null) {
    return `صيغةٌ غير مدعومة${mime ? ` (${mime})` : ''} — المدعوم: ${SUPPORTED}`
  }
  return null
}
