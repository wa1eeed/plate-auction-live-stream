/**
 * **تحقّقُ هويّة المشتري — قبل أن تصل أبشر.**
 *
 * ورقمٌ خاطئٌ لا يُردّ في المنصّة بل في أبشر، بعد أن يكون البائعُ فتح
 * الخدمةَ وأدخل ومضى — فيرجع بلا سببٍ مفهوم. ويُقاس هنا ما يُقاس بيقين:
 * **عشرُ خاناتٍ تبدأ بـ١ (مواطن) أو ٢ (مقيم)**، وهي قاعدةُ أرقام الهوية
 * السعودية. وما وراء ذلك — أنّ الرقم لفلانٍ بعينه — لا تعرفه إلّا أبشر.
 *
 * والتاريخُ يُقاس شكلًا ومدًى: `YYYY-MM-DD`، وسنةٌ تسع الهجريَّ والميلاديَّ
 * معًا فلا يُرفض تقويمٌ صحيح.
 */
export type IdentityError = 'ID_FORMAT' | 'DATE_FORMAT' | 'DATE_RANGE'

export function validateTransferIdentity(input: {
  nationalId: string
  birthDate: string
  birthCalendar: string
}): IdentityError | null {
  if (!/^[12]\d{9}$/.test(input.nationalId)) return 'ID_FORMAT'
  if (!/^\d{4}-\d{2}-\d{2}$/.test(input.birthDate)) return 'DATE_FORMAT'

  const [year, month, day] = input.birthDate.split('-').map(Number)
  if (month < 1 || month > 12 || day < 1 || day > 31) return 'DATE_FORMAT'
  /*
   * المدى يسع التقويمين: الهجريُّ اليوم في الـ١٤٠٠ وما بعدها، والميلاديُّ
   * في الـ١٩٠٠ وما بعدها. فحدٌّ أدنى عند ١٣٠٠ وأعلى عند سنةٍ قادمة يردّ
   * الخطأ الجسيم (سنةٌ من ثلاث خانات، أو تاريخٌ في المستقبل البعيد) ولا
   * يردّ تقويمًا صحيحًا.
   */
  const thisYear = new Date().getFullYear()
  if (year < 1300 || year > thisYear + 1) return 'DATE_RANGE'
  return null
}

