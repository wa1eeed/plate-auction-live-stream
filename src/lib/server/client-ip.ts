/**
 * عنوان الزائر الحقيقيّ — من خلف وكيلٍ عكسيّ أو شبكة توصيل.
 *
 * والمنصّة لا تُخاطَب مباشرةً: يقف أمامها Traefik في كوليفاي، وقد يقف أمامه
 * كلاودفلير. فكلُّ طلبٍ يصل بعنوان **الوكيل** لا الزائر، والعنوان الحقيقيّ
 * في ترويسة.
 *
 * ⚠ **وهذه الترويسات تُزوَّر** إن كان الأصل مكشوفًا للإنترنت مباشرةً: يكتبها
 * المهاجم بما شاء فيلبس ألف عنوان. والحارس ليس في الكود بل في الشبكة —
 * ألّا يُقبل على الأصل إلّا ما جاء من الوكيل (انظر `docs/security.md`).
 */

/** بالترتيب: الأخصّ فالأعمّ. أوّلُ ما يوجد يُؤخذ. */
const SOURCES = [
  /* كلاودفلير يضعه ويستبدل ما كان — فلا يُمرَّر مزوَّرًا من الخارج عبره */
  'cf-connecting-ip',
  /* المعيار: قائمةٌ يضيف كلّ وكيلٍ نفسه إلى آخرها، وأوّلُها الزائر */
  'x-forwarded-for',
  'x-real-ip',
] as const

export function clientIp(headers: Headers): string {
  for (const name of SOURCES) {
    const raw = headers.get(name)
    if (!raw) continue
    const first = raw.split(',')[0]?.trim()
    if (first) return first
  }
  /*
   * لا عنوان: يقع في الاختبار وفي طلبٍ داخليّ. وثابتٌ واحد لا قيمةٌ عشوائية:
   * العشوائيّ يمنح كلَّ طلبٍ نافذةً جديدة فيُلغي الحدَّ من حيث أُريد له أن يحرس.
   */
  return 'unknown'
}
