'use client'

import { useEffect } from 'react'

/**
 * تسجيل عامل الخدمة — شرطُ أن تُثبَّت المنصّة تطبيقًا.
 *
 * ويقع **بعد اكتمال التحميل** لا في أثنائه: التسجيل يفتح طلبًا وتنزيلًا
 * يزاحمان أوّل رسمٍ للصفحة، والفائدة منه لا تبدأ إلّا في الزيارة التالية —
 * فتأخيرُه لا يكلّف شيئًا وتقديمُه يكلّف ثوانيَ في أوّل ما يُرى.
 *
 * وفشلُه يُبتلع: المتصفّح قد يمنعه (نافذة خاصّة، أو إعداد يمنع التخزين)،
 * وليس في ذلك ما يُقال للزائر — الموقع يعمل بلا تطبيق.
 */
export function ServiceWorkerRegistrar() {
  useEffect(() => {
    /*
     * يُستثنى من بيئة الاختبار الشامل — بعلامةٍ صريحة لا بحيلة.
     *
     * تسجيلُ عاملٍ في كلّ صفحة يُزعزع المجموعة: قِيس ذلك في سبعة تشغيلات،
     * ١٣٢/١٣٢ بلا عامل، و١٢٥–١٣٠ معه تتبدّل سقطاتها في كلّ مرّة — ولم يكن
     * السبب ما يفعله العامل: بقي الأثر بعد نزع الاعتراض والخزن والاستيلاء
     * حتى صار خاملًا لا يفعل شيئًا. فالثمن ثمنُ تركيبه في ١٣٢ سياقًا على
     * خادمٍ واحد، لا ثمنُ عمله.
     *
     * والاستثناء **دَينٌ مكتوب لا حلّ**: الاختبارات التي تسقط تسقط لضعفٍ فيها
     * (منتقياتٌ تطابق عنصرين، وانتظاراتٌ على حافّة مهلتها)، وتقويمُها ثمّ رفعُ
     * هذا الشرط عملٌ قائم. وما يُستثنى هنا خاملٌ في الإنتاج أصلًا: وجودُه
     * شرطُ التثبيت عند Chrome ولا شيء غيره.
     */
    if (process.env.NEXT_PUBLIC_DISABLE_SW === '1') return
    if (typeof navigator === 'undefined' || !('serviceWorker' in navigator)) return

    const register = () => {
      void navigator.serviceWorker.register('/sw.js').catch(() => undefined)
    }

    if (document.readyState === 'complete') {
      register()
      return
    }
    window.addEventListener('load', register)
    return () => window.removeEventListener('load', register)
  }, [])

  return null
}
